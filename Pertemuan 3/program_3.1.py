# Operasi Aritmatika di Python

a = 10
b = 3

# Operasi Penjumlahan (Tambah +)
hasil = a + b
print("Hasil Penjumlahan dari", a, "+", b, "adalah", hasil)

# Operasi Pengurangan (Kurang -)
hasil = a - b
print("Hasil Pengurangan dari", a, "-", b, "adalah", hasil)

# Operasi Perkalian (Kali *)
hasil = a * b
print("Hasil Perkalian dari", a, "*", b, "adalah", hasil)

# Operasi Pembagian (Bagi /)
hasil = a / b
print("Hasil Pembagian dari", a, "/", b, "adalah", hasil)

# Operasi Pemangkatan (Pangkat **)
hasil = a ** b
print("Hasil Pemangkatan dari", a, "**", b, "adalah", hasil)

# Operasi Modulus (Sisa Bagi %)
hasil = a % b
print("Hasil Modulus dari", a, "%", b, "adalah", hasil)

# Operasi Floor Division (Pembagian Bulat //)
hasil = a // b
print("Hasil Floor Division dari", a, "//", b, "adalah", hasil)