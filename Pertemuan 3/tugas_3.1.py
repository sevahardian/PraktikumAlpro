panjang = 12
lebar = 5
tinggi = 8
luas = panjang * lebar
volume = panjang * lebar * tinggi
keliling = 2 * (panjang + lebar)

# a. Hitunglah luas, volume, dan keliling bangunan tersebut!
print("Luas permukaan bangunan adalah", luas, "cm^2")
print("Volume bangunan adalah", volume, "cm^3")
print("Keliling bangunan adalah", keliling, "cm")

# b. Apakah luas bangunan lebih dari 50 cm^2
print("Luas bangunan lebih dari 50 cm^2:", luas > 50)

# c. Apakah volume bangunan bernilai 480 cm^3
print("Volume bangunan sama dengan 480 cm^3:", volume == 480)