# 1. Konversi angka_string menjadi integer
angka_string = "123"

# Membuat variabel baru untuk mengubah tipe data variabel angka_string menjadi integer dengan int()
konversi_angka_string = int(angka_string)
print (konversi_angka_string, ", data ini telah terkonversi menjadi tipe data", type(konversi_angka_string), "yang awalnya adalah", angka_string, "bertipe data", type(angka_string))

