nama = input("Siapakah nama anda?") 
 
# 1. Program IF-INLINE
if nama == "anaxa" : print("Kamu ganteng abieeezz!!!") 
print("Akhir dari program IF-INLINE") 
 
# 2. Program IF-INDENTATION 
if nama == "phainon": 
    print("Kamu ganteng abieeezz!!!") 
    print("Kamu juga Keren bangeeetzz!!!") 
print("Akhir dari program IF-INDENTATION") 
 
# 3. Program ELSE STATEMENT
if nama == "sunday": 
   print("Hai Sunday, si Kereeenzz!!!") 
else: 
   print("Ah kamu bukan Sunday, kamu gak keren, cuih!!!") 
 
print("Akhir dari program ELSE STATEMENT")