# ELIF = ELSE IF STATEMENT
nama = input("Siapakah nama anda? ") 

# IF kondisi: 
#   aksi true 
# ELIF kondisi: 
#   aksi true 
# ELIF kondisi: 
#   aksi true 
# else: 
#   aksi 

if nama == "anaxa": # kondisi 1 
    print("Hai ganteng abiiz!!!") # aksi TRUE 1 
elif nama == "phainon": # kondisi 2 
    print("Hai si kece bangeeetzz!!!") # aksi TRUE 2 
elif nama == "sunday": # kondisi 3
    print("Hai humoris!!!") # aksi TRUE 3 
else: 
    print("Au ah malaz gak kenal!!!") # aksi FALSE 

print("Akhir dari program ELIF STATEMENT")